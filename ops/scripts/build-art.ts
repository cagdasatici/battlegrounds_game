// Regenerates the original art files and the asset manifest (task T25).
// Usage: pnpm assets:build   (writes assets/fighters/*.gltf, assets/manifest.json, assets/provenance.csv)
// Every fighter file is generated from packages/shared/src/rig.ts and fighterDesign.ts; nothing is imported from outside the repo.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { csvCell, KITS, PROVENANCE_COLUMNS, type ManifestEntry } from "../../packages/shared/src/art.js";
import { FIGHTER_DESIGNS } from "../../packages/shared/src/fighterDesign.js";
import { buildFighterGltf } from "./art-gltf.js";

const root = new URL("../../", import.meta.url);
const GENERATED_ON = "2026-11-01";
const LICENSE = "Project-original work; no third-party material; rights held by the project owner";
const AUTHOR = "Elemental Battlegrounds project (code authored in repository by Claude Code under owner direction)";
const sha = (b: Buffer): string => createHash("sha256").update(b).digest("hex");
const file = (rel: string): Buffer => readFileSync(new URL(rel, root));

mkdirSync(new URL("assets/fighters/", root), { recursive: true });
const assets: ManifestEntry[] = [];

for (const kit of KITS) {
  const g = buildFighterGltf(kit);
  const rel = `assets/fighters/${kit}.gltf`;
  writeFileSync(new URL(rel, root), g.json);
  const buf = file(rel);
  assets.push({
    id: `fighter.${kit}`, kind: "fighter", path: rel, sha256: sha(buf), byteSize: buf.length, license: LICENSE, author: AUTHOR,
    source: "repo:ops/scripts/art-gltf.ts from packages/shared/src/rig.ts and fighterDesign.ts",
    creationMethod: "procedural-code", rigVersion: g.rigVersion, bounds: g.bounds, kit, clips: g.clips,
    notes: `${FIGHTER_DESIGNS[kit].label}: skinned vertex-coloured model with ${g.clips.length} clips`,
  });
}
// ART1: third party CC0 environment models, copied verbatim from the pack (textures downscaled to 512 px).
const VENDOR_DIR = "assets/vendor/quaternius-stylized-nature";
for (const name of readdirSync(new URL(`${VENDOR_DIR}/`, root)).sort()) {
  const rel = `${VENDOR_DIR}/${name}`;
  const buf = file(rel);
  assets.push({
    id: `env.quaternius.${name}`, kind: "environment", path: rel, sha256: sha(buf), byteSize: buf.length, license: "CC0-1.0", author: "Quaternius",
    source: "https://quaternius.com/packs/stylizednaturemegakit.html", creationMethod: "third-party CC0 pack",
    notes: name.endsWith(".png") ? "Stylized Nature MegaKit (Standard) texture, downscaled to 512 px" : "Stylized Nature MegaKit (Standard) file, unmodified",
  });
}
const mapBuf = file("assets/maps/islands.v1.json");
assets.push({
  id: "map.islands.v1", kind: "map", path: "assets/maps/islands.v1.json", sha256: sha(mapBuf), byteSize: mapBuf.length, license: LICENSE, author: AUTHOR,
  source: "repo:packages/shared/src/config/arena.ts buildIslandsMap()", creationMethod: "procedural-code", notes: "Collision map; regenerated by content:validate --write",
});
const arenaBuf = file("apps/client/src/scene/ArenaView.ts");
assets.push({
  id: "code.arena-view", kind: "code", path: "apps/client/src/scene/ArenaView.ts", sha256: sha(arenaBuf), byteSize: arenaBuf.length, license: LICENSE, author: AUTHOR,
  source: "repo:apps/client/src/scene/ArenaView.ts", creationMethod: "hand-authored-code",
  notes: "Arena, sky, clouds and islet visuals are built at runtime from this file; hashed so a change must be re-recorded here",
});

writeFileSync(new URL("assets/manifest.json", root), JSON.stringify({ schemaVersion: 1, generator: "ops/scripts/build-art.ts", assets }, null, 2) + "\n");
const rows: string[] = [PROVENANCE_COLUMNS.join(",")];
for (const a of assets) rows.push([a.id, a.path, a.author, a.license, a.creationMethod, a.source, GENERATED_ON, a.notes ?? ""].map(csvCell).join(","));
writeFileSync(new URL("assets/provenance.csv", root), rows.join("\n") + "\n");
console.log(`wrote ${assets.length} manifest entries; fighters: ${assets.filter((a) => a.kind === "fighter").map((a) => `${a.id} ${a.byteSize} B`).join(", ")}`);
